# ─────────────────────────────────────────────────────────────────────────────
# Embeds the code-signing certificate into the NSIS installer script.
# Run this BEFORE build-signed.ps1 each time you rebuild the installer.
#
# Usage:
#   Right-click → Run with PowerShell (no admin needed)
# ─────────────────────────────────────────────────────────────────────────────

$ErrorActionPreference = 'Stop'

$cerPath    = "C:\certs\topten.cer"
$projectRoot = Split-Path -Parent $PSScriptRoot
$buildDir   = Join-Path $projectRoot "build"
$nshPath    = Join-Path $buildDir "installer.nsh"

if (-not (Test-Path $cerPath)) {
    Write-Host "ERROR: $cerPath not found. Run create-cert.ps1 first." -ForegroundColor Red
    exit 1
}

# Read the certificate and encode it as Base64
$certBytes  = [System.IO.File]::ReadAllBytes($cerPath)
$certBase64 = [Convert]::ToBase64String($certBytes)

# Build a PowerShell command that decodes + installs the cert from memory
$psCommand = @"
`$cert = [Convert]::FromBase64String('$certBase64')
`$tmp  = [System.IO.Path]::GetTempFileName() + '.cer'
[System.IO.File]::WriteAllBytes(`$tmp, `$cert)
Import-Certificate -FilePath `$tmp -CertStoreLocation Cert:\LocalMachine\Root            | Out-Null
Import-Certificate -FilePath `$tmp -CertStoreLocation Cert:\LocalMachine\TrustedPublisher | Out-Null
Remove-Item `$tmp -Force
"@

# Base64-encode the entire PS command for -EncodedCommand (UTF-16LE required)
$psBytes   = [System.Text.Encoding]::Unicode.GetBytes($psCommand)
$psEncoded = [Convert]::ToBase64String($psBytes)

# Create build\ folder if needed
if (-not (Test-Path $buildDir)) {
    New-Item -ItemType Directory -Path $buildDir | Out-Null
}

# Write installer.nsh with the cert embedded
$nshContent = @"
; Auto-generated by prepare-build.ps1 — do not edit manually.
; Installs the trusted publisher certificate during NSIS setup.

!macro customInstall
  DetailPrint "Installing trusted publisher certificate..."
  nsExec::ExecToLog 'powershell.exe -ExecutionPolicy Bypass -NonInteractive -EncodedCommand $psEncoded'
  DetailPrint "Certificate installed."
!macroend
"@

[System.IO.File]::WriteAllText($nshPath, $nshContent, [System.Text.Encoding]::UTF8)

Write-Host ""
Write-Host "installer.nsh generated with embedded certificate." -ForegroundColor Green
Write-Host "Now run scripts\build-signed.ps1 to build the installer."
